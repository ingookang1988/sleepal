/** frontmatter 원문 추출(순수). 없으면 null. */
function frontmatter(txt) {
  const m = String(txt || '').match(/^(?:\s|<!--[\s\S]*?-->)*---\r?\n([\s\S]*?)\r?\n---/);
  return m ? m[1] : null;
}

/** 스칼라 필드(순수). 따옴표는 벗긴다. */
function field(fm, key) {
  const m = String(fm || '').match(new RegExp('^[ \\t]*' + key + ':[ \\t]*(.*)$', 'm'));
  if (!m) return null;
  return m[1].trim().replace(/^["']|["']$/g, '').trim() || null;
}

/** 리스트 필드(순수). 인라인 `[a, b]` 와 블록 `- a` 를 모두 받는다. */
function listField(fm, key) {
  const s = String(fm || '');
  const inline = s.match(new RegExp('^[ \\t]*' + key + ':[ \\t]*\\[(.*?)\\][ \\t]*$', 'm'));
  if (inline) {
    return inline[1].split(',').map(x => x.trim().replace(/^["']|["']$/g, '')).filter(Boolean);
  }
  const head = s.match(new RegExp('^[ \\t]*' + key + ':[ \\t]*$', 'm'));
  if (!head) return [];
  // head[0]은 `$`(m 플래그)로 줄 끝에서 끝나므로 잔여물의 첫 조각은 항상 빈 문자열이다 — 버린다.
  const rest = s.slice(head.index + head[0].length).split(/\r?\n/).slice(1);
  const out = [];
  for (const line of rest) {
    const item = line.match(/^[ \t]*-[ \t]+(.*)$/);
    if (!item) break;
    const v = item[1].trim().replace(/^["']|["']$/g, '');
    if (v) out.push(v);
  }
  return out;
}

/** 발행 계약의 필수 3절(sprint/_GUIDE §Anatomy — [PRO-19]가 산문을 검사로 이행). */
const REQUIRED_SECTIONS = ['목표', '수용 기준', '증거'];

/**
 * WO 문서 텍스트 → 레코드(순수). WO 가 아니면 null, frontmatter 없으면 malformed.
 * cfg(adapter 설정, [PRO-27] ②): status 는 statusMap 으로 매핑(원문은 rawStatus), evidence·closed_by 는 상류 필드 → 별칭 순으로 읽는다.
 */
function parseWo(relFile, txt, cfg = null) {
  const base = relFile.split('/').pop();
  const p = parse(base);
  if (!p || p.domain !== 'WO') return null;
  // [PRO-28] ①②: 절은 adapter.json sections 별칭 맵으로 해소(맵 없음 = 상류 표기 정확·접두 — 현행과 동일).
  let missingSections = sectionsMissing(cfg, txt);
  const fm = frontmatter(txt);
  if (!fm) return { id: p.id, file: relFile, status: null, parent: null, evidence: null, closed_by: [], missingSections, malformed: true };
  const raw = field(fm, 'status');
  const pick = key => { for (const k of fieldAliases(cfg, key)) { const v = field(fm, k); if (v) return v; } return null; };
  const pickList = key => { for (const k of fieldAliases(cfg, key)) { const v = listField(fm, k); if (v.length) return v; } return []; };
  // 증거는 절이 없어도 frontmatter evidence: 로 충족([PRO-28] ① — 어답터 실측: `## 증거` 0건, 증거는 frontmatter).
  if (pick('evidence')) missingSections = missingSections.filter(s => s !== '증거');
  return {
    id: p.id,
    file: relFile,
    title: field(fm, 'title'),
    status: mapStatus(cfg, raw),
    rawStatus: raw,
    parent: field(fm, 'parent'),
    evidence: pick('evidence'),
    closed_by: pickList('closed_by'),
    missingSections,
    malformed: false,
  };
}

/**
 * 발행 점검(순수) — [PRO-19] ①, 종료 의례의 상류 대칭. index: zfs_index 레코드 배열.
 * parent 는 도메인까지 맞아야 실존이다 — ID 만 대조하면 다른 도메인의 우연한 동일 계보
 * (예: FLOW-01a)가 죽은 부모(PLAN-01a)를 가려 준다.
 */
function checkIssuance(wo, index = []) {
  if (!wo) return [];
  if (wo.malformed) {
    return [{ code: 'no-frontmatter', outcome: 'CLARIFY', msg: 'WO 문서에 frontmatter 가 없다 — 발행 계약(status·parent·evidence)을 읽을 수 없다.' }];
  }
  const issues = [];
  if (wo.missingSections && wo.missingSections.length) {
    issues.push({
      code: 'anatomy-missing', outcome: 'CLARIFY',
      msg: `필수 절 누락: ${wo.missingSections.map(s => '## ' + s).join(' · ')} (sprint/_GUIDE §Anatomy). 다른 표기를 쓴다면 adapter.json sections 별칭 맵으로 읽힌다([PRO-28] — 문서는 안 고친다).`,
    });
  }
  if (!wo.parent) {
    issues.push({ code: 'no-parent', outcome: 'CLARIFY', msg: 'frontmatter parent: 가 없다 — 상위 축(PLAN/PRO 등)을 명시하라.' });
  } else {
    const m = String(wo.parent).match(/^([A-Z]{2,6})-/);
    const pid = parseId(String(wo.parent));
    if (!m || !pid || !index.some(d => d.domain === m[1] && d.id === pid)) {
      issues.push({ code: 'parent-missing', outcome: 'CLARIFY', msg: `parent(${wo.parent})가 색인에 없다 — 오타이거나 상위 문서 미작성(죽은 부모).` });
    }
    // 산술 상속이 적용되는 구간에서만 묻는다([PRO-27] ③) — 레거시 독립 채번·전역 일련번호 구간은 frontmatter 부모가 정본이다.
    const rec = index.find(d => d.domain === 'WO' && d.id === wo.id);
    const arithmetic = !rec || rec.arithmetic !== false;
    if (pid && arithmetic && !isDescendant(pid, wo.id)) {
      issues.push({ code: 'lineage-break', outcome: 'CLARIFY', msg: `parent(${wo.parent})와 이 WO(${wo.id})의 계보가 산술로 이어지지 않는다 — 플릿 파티션([PRO-05])이 오분할된다. 독립 채번 구간이면 adapter.json lineage.arithmeticFrom 으로 선언하라([PRO-27] ③).` });
    }
  }
  return issues;
}

/** 이 WO(또는 조상)를 가리키는 브래킷 참조가 텍스트에 있는가(순수). */
function mentionsLineage(txt, woId) {
  const ids = [woId, ...ancestorChain(woId).slice(1)];
  return ids.some(id => new RegExp('\\[[A-Z]{2,6}-' + id.replace(/[-]/g, '\\-') + '\\]').test(String(txt || '')));
}

/**
 * 닫힘 점검(순수). traceTexts: {경로: 본문} — 호출부가 읽어 넘긴다.
 * siblings: 같은 부모를 공유하는 WO 레코드들(부모 전이 후보 판정용).
 * phases: 이 계보의 PHASE 레코드들([PRO-19] ② — 로드맵은 Schema 라 되쓰지 않고 검토 후보로만 제시).
 */
function checkClosure(wo, traceTexts = {}, siblings = [], phases = [], receiptCtx = null) {
  const issues = [];
  if (!wo || wo.malformed) {
    issues.push({ code: 'no-frontmatter', outcome: 'CLARIFY', msg: 'WO 문서에 frontmatter 가 없다 — status·evidence·closed_by 를 읽을 수 없다.' });
    return { issues, info: [] };
  }
  if (!wo.closed_by.length) {
    issues.push({
      code: 'no-trace', outcome: 'CLARIFY',
      msg: '상위 축 흔적(closed_by)이 비었다. 후보: ' + TRACE_CANDIDATES.join(' · '),
    });
  }
  for (const p of wo.closed_by) {
    const txt = traceTexts[p];
    if (txt == null) {
      issues.push({ code: 'trace-missing', outcome: 'CLARIFY', msg: `closed_by 가 가리킨 파일을 읽을 수 없다: ${p}` });
    } else if (!mentionsLineage(txt, wo.id)) {
      // 선언만 하고 반영하지 않은 경우 — 흔적을 *확인 가능한 사실*로 만드는 검사.
      issues.push({ code: 'trace-unreferenced', outcome: 'CLARIFY', msg: `${p} 에 이 계보(${wo.id}) 참조가 없다 — 선언만 하고 반영하지 않았는가?` });
    }
  }
  if (!wo.evidence) {
    issues.push({
      code: 'no-evidence', outcome: 'CLARIFY',
      msg: '증거(evidence)가 비었다. 값을 적거나, 없으면 `none — 이유`로 명시하라(미기입과 해당없음의 구별).',
    });
  }
  // 영수증 인용([PRO-22] 단계 2): 선언 검사(adapter.checks)가 있는 레포에서 실값 증거는 러너가 쓴 영수증을 인용해야 한다 —
  // `rcpt:<검사명>@<sha>` 또는 `rcpt:n/a — 이유`(소급 없음 — 신규 WO 부터). 수기 영수증 경로는 없다: 인용은 receipts.md 의 실제 줄과 대조한다.
  if (receiptCtx && receiptCtx.declared && wo.evidence && !/^none\b/i.test(wo.evidence)) {
    const { refs, na } = receipts.citations(wo.evidence);
    if (!refs.length && !na) {
      issues.push({ code: 'no-receipt', outcome: 'CLARIFY', msg: 'evidence 가 영수증을 인용하지 않는다 — `rcpt:<검사명>@<sha>`(ci.js 가 쓴 receipts.md 줄) 또는 `rcpt:n/a — 이유`([PRO-22] 단계 2, 소급 없음).' });
    }
    for (const r of refs) {
      if (!(receiptCtx.receipts || []).some(x => x.name === r.name && String(x.sha || '').startsWith(r.sha.slice(0, 7)))) {
        issues.push({ code: 'receipt-missing', outcome: 'CLARIFY', msg: `인용한 영수증이 없다: rcpt:${r.name}@${r.sha} — receipts.md 에 그 검사·커밋 줄이 없다(수기 인용인가?).` });
      }
    }
  }
  const info = [];
  const others = siblings.filter(s => s.id !== wo.id);
  if (others.length && others.every(s => s.status === 'Closed')) {
    info.push(`부모(${wo.parent || ancestorChain(wo.id)[1] || '?'})의 자식 WO 가 모두 Closed 다 — PLAN status 전이 후보(강제 아님).`);
  }
  if (phases.length) {
    info.push(`계보의 로드맵 ${phases.map(p => `[PHASE-${p.id}]`).join(' ')} — exit criteria 검토 후보(강제 아님, [PRO-19]).`);
  }
  return { issues, info };
}

/** 활성 WO 목록 → 작업대 표 본문(순수, id 정렬). */
function buildTable(wos) {
  const rows = wos
    .filter(w => w && ACTIVE.has(w.status))
    .sort((a, b) => a.id.localeCompare(b.id))
    .map(w => {
      const parent = w.parent || ancestorChain(w.id)[1] || '—';
      const ev = w.evidence ? (/^none\b/i.test(w.evidence) ? '해당없음' : '있음') : '—';
      // 파생 라벨([PRO-26] ④): 레코드에 label 이 있으면 `[WO-id · label]` — 없으면(순수 테스트·구버전) 기존 꼴.
      return `| ${renderId('WO', w.id, w.label || null)} | ${w.title || '—'} | ${parent} | ${w.status} | ${ev} |`;
    });
  const head = '| WO | 제목 | 부모 | 상태 | 증거 |\n|---|---|---|---|---|';
  return rows.length ? `${head}\n${rows.join('\n')}` : `${head}\n| — | 활성 WO 없음 | — | — | — |`;
}

/** next.md 마커 블록에 주입(순수). 마커 없으면 null. 지배적 EOL 보존. */
function inject(nextTxt, table) {
  if (!BLOCK_RE.test(nextTxt)) return null;
  const eol = (nextTxt.match(/\r\n/g) || []).length > (nextTxt.match(/(?<!\r)\n/g) || []).length ? '\r\n' : '\n';
  const body = table.split('\n').join(eol);
  return nextTxt.replace(BLOCK_RE, (_, b, __, e) => `${b}${eol}${body}${eol}${e}`);
}

function gather(root = path.resolve(__dirname, '..')) {
  const out = [];
  const cfg = loadAdapter(root);
  walkFiles(root, SPRINT_DIR, rel => {
    if (!rel.endsWith('.md')) return;
    let rec = null;
    try { rec = parseWo(rel, fs.readFileSync(path.join(root, rel), 'utf8'), cfg); } catch { rec = null; }
    if (rec) out.push(rec);
  });
  return out;
}

function readTraces(root, paths) {
  const out = {};
  for (const p of paths) {
    try { out[p] = fs.readFileSync(path.join(root, p), 'utf8'); } catch { /* 읽기 실패는 checkClosure 가 판정 */ }
  }
  return out;
}

function run(argv = process.argv.slice(2), root = path.resolve(__dirname, '..')) {
  const wos = gather(root);
  const json = argv.includes('--json');

  if (argv.includes('--table')) {
    // 발행 점검([PRO-19] ①) — 활성(및 frontmatter 불능) WO 전수. 표면화만, 뷰 생성을 막지 않는다.
    const index = buildIndex(root);
    const labels = labelMap(index);
    for (const w of wos) w.label = labels.get(`WO-${w.id}`) || null;
    const issuance = wos
      .filter(w => w.malformed || ACTIVE.has(w.status))
      .flatMap(w => checkIssuance(w, index).map(i => ({ id: w.id, ...i })));
    const surface = () => {
      if (!issuance.length) return;
      console.error('\n[work-close] 발행 계약 미충족 (CLARIFY — 차단하지 않는다, [PRO-19]):');
      issuance.forEach(i => console.error(`  ? WO-${i.id} ${i.code}: ${i.msg}`));
    };
    const nextPath = path.join(root, NEXT);
    // 손 이식 어답터엔 next.md 가 없다(어답터 C 실측: ENOENT 크래시) — --write 는 마커 블록을 가진 뷰를 만들고, 검사는 CLARIFY 로 묻는다.
    let current;
    try { current = fs.readFileSync(nextPath, 'utf8'); } catch {
      if (!argv.includes('--write')) { console.error(`work-close: ${NEXT} 없음 — \`node scripts/work-close.js --table --write\` 로 작업대 뷰를 만들어라.`); surface(); return OUTCOME.CLARIFY; }
      // 어답터에 쓰는 생성 파일의 상류 ID 는 [up:ID]([WO-29a-3] — 로컬 PRO-15 가 없는 어답터의 ref-linter --strict Fail-close, C 실측).
      current = isTemplateRepo(root) ? NEXT_SKELETON : prefixUpstreamRefs(NEXT_SKELETON);
    }
    const expected = inject(current, buildTable(wos));
    if (expected === null) {
      console.error('work-close: next.md 에 마커 블록(<!-- worktable:begin/end -->)이 없음 — 블록을 먼저 추가하라.');
      surface();
      return OUTCOME.CLARIFY;
    }
    if (argv.includes('--write')) {
      if (expected !== current) { fs.writeFileSync(nextPath, expected); console.log('work-close: next.md 작업대 뷰 갱신.'); }
      else console.log('work-close: 작업대 뷰 이미 최신.');
      surface();
      return issuance.length ? OUTCOME.CLARIFY : OUTCOME.PASS;
    }
    if (expected !== current) {
      console.error('work-close: next.md 작업대 뷰가 WO 문서와 불일치(드리프트) — `node scripts/work-close.js --table --write` 실행.');
      surface();
      return OUTCOME.CLARIFY;
    }
    console.log(`work-close 통과: 활성 WO ${wos.filter(w => ACTIVE.has(w.status)).length}건, 작업대 뷰 동기화됨.`);
    surface();
    return issuance.length ? OUTCOME.CLARIFY : OUTCOME.PASS;
  }

  const target = argv.find(a => !a.startsWith('--'));
  if (!target) {
    console.error('사용법: node scripts/work-close.js <WO-ID> | --table [--write]');
    return OUTCOME.CLARIFY;
  }
  const id = target.replace(/^WO-/, '');
  const wo = wos.find(w => w.id === id);
  if (!wo) {
    console.error(`work-close: WO-${id} 문서를 ${SPRINT_DIR} 에서 찾지 못했다.`);
    return OUTCOME.CLARIFY;
  }
  const parentId = wo.parent || ancestorChain(wo.id)[1] || null;
  const siblings = wos.filter(w => (w.parent || ancestorChain(w.id)[1] || null) === parentId);
  const chain = new Set(ancestorChain(wo.id));
  const phases = buildIndex(root).filter(d => d.domain === 'PHASE' && chain.has(d.id));
  const cfgClose = loadAdapter(root);
  const receiptCtx = { declared: (cfgClose.checks || []).length > 0, receipts: receipts.parseReceipts(receipts.read(root) || '') };
  const { issues, info } = checkClosure(wo, readTraces(root, wo.closed_by), siblings, phases, receiptCtx);

  if (json) { console.log(JSON.stringify({ wo, issues, info }, null, 2)); return issues.length ? OUTCOME.CLARIFY : OUTCOME.PASS; }

  console.log(`# work-close ${target} — status: ${wo.status || '(미기입)'}${wo.rawStatus && wo.rawStatus !== wo.status ? ` (로컬 어휘 ${wo.rawStatus} → statusMap)` : ''}`);
  if (info.length) info.forEach(i => console.log(`  · ${i}`));
  if (!issues.length) {
    console.log(`  ✓ 닫힘 조건 충족 — 흔적 ${wo.closed_by.length}곳 · 증거 명시됨.`);
    console.log('  → 세션 종료 시 이 문서를 .union-stack/sprint/archived/ 로 옮기고 `--table --write` 로 뷰를 갱신하라([PRO-15]).');
    return OUTCOME.PASS;
  }
  console.error('\n[work-close] 닫힘 조건 미충족 (CLARIFY — 차단하지 않는다):');
  issues.forEach(i => console.error(`  ? ${i.code}: ${i.msg}`));
  return OUTCOME.CLARIFY;
}

